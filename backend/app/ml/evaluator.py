import os
import json
import torch
import numpy as np
import networkx as nx
from typing import Dict, Any, List, Optional
from .dataset_generator import extract_node_features
from .gnn_model import TaskRiskGraphSAGE

SAVED_MODELS_DIR = os.getenv("MODELS_DIR", os.path.join(os.path.dirname(__file__), "..", "..", "saved_models"))

_GNN_MODEL_INSTANCE: Optional[TaskRiskGraphSAGE] = None

def get_trained_gnn_model() -> Optional[TaskRiskGraphSAGE]:
    """Loads and caches the trained GNN weights if available."""
    global _GNN_MODEL_INSTANCE
    if _GNN_MODEL_INSTANCE is not None:
        return _GNN_MODEL_INSTANCE

    weights_path = os.path.join(SAVED_MODELS_DIR, "gnn_risk_model.pt")
    if not os.path.exists(weights_path):
        return None

    try:
        model = TaskRiskGraphSAGE(in_channels=10, hidden_channels=32, num_classes=2, dropout=0.0)
        model.load_state_dict(torch.load(weights_path, map_location=torch.device("cpu")))
        model.eval()
        _GNN_MODEL_INSTANCE = model
        return _GNN_MODEL_INSTANCE
    except Exception as e:
        print(f"Warning: Failed to load GNN model weights: {e}")
        return None

def load_evaluation_report() -> Dict[str, Any]:
    """Reads the saved evaluation results JSON file generated by train.py."""
    results_path = os.path.join(SAVED_MODELS_DIR, "evaluation_results.json")
    if os.path.exists(results_path):
        with open(results_path, "r", encoding="utf-8") as f:
            return json.load(f)

    # If not yet trained, return an un-trained status object
    return {
        "dataset_type": "Synthetic meeting dependency benchmark (Not Yet Executed)",
        "dataset_stats": {},
        "research_question": "Can graph representation learning improve task-risk classification by incorporating task dependencies and neighbouring task information, compared with models that consider each task independently?",
        "gnn_metrics": {
            "model_name": "GraphSAGE", "accuracy": 0.0, "precision": 0.0, "recall": 0.0, "f1_score": 0.0, "confusion_matrix": [[0, 0], [0, 0]]
        },
        "baseline_metrics": {
            "model_name": "Logistic Regression", "accuracy": 0.0, "precision": 0.0, "recall": 0.0, "f1_score": 0.0, "confusion_matrix": [[0, 0], [0, 0]]
        },
        "conclusion": "Model training has not been executed yet. Please trigger training via backend/app/ml/train.py or the API.",
        "limitations": [],
        "is_trained": False
    }

def run_gnn_inference_on_tasks(tasks: List[Dict[str, Any]], G: nx.DiGraph) -> List[Dict[str, Any]]:
    """
    Applies the trained GNN model to calculate task-risk probabilities
    for each task in the provided graph.
    """
    model = get_trained_gnn_model()
    if not tasks:
        return tasks

    if model is None:
        # Fallback heuristic if weights haven't been trained yet
        for t in tasks:
            t["gnn_risk_prob"] = 0.25
            t["gnn_risk_label"] = "LOW"
        return tasks

    # Build node feature matrix
    node_to_idx = {t["id"]: i for i, t in enumerate(tasks)}
    x_list = [extract_node_features(t, G) for t in tasks]
    x_tensor = torch.tensor(np.array(x_list), dtype=torch.float32)

    # Build bidirectional edge index for message passing
    edge_src = []
    edge_dst = []
    for u, v in G.edges():
        if u in node_to_idx and v in node_to_idx:
            edge_src.extend([node_to_idx[u], node_to_idx[v]])
            edge_dst.extend([node_to_idx[v], node_to_idx[u]])

    if len(edge_src) > 0:
        edge_index = torch.tensor([edge_src, edge_dst], dtype=torch.long)
    else:
        edge_index = torch.empty((2, 0), dtype=torch.long)

    model.eval()
    with torch.no_grad():
        probs = model.predict_proba(x_tensor, edge_index)

    for i, t in enumerate(tasks):
        risk_prob = float(probs[i, 1].item())
        t["gnn_risk_prob"] = round(risk_prob, 3)
        t["gnn_risk_label"] = "AT_RISK" if risk_prob >= 0.50 else "LOW"

    return tasks
